#!/usr/bin/env node
/*
 * Builds assets/js/search-index.js from the site's HTML pages.
 *
 * Usage:  node scripts/build-search-index.mjs
 *
 * Each page is split into sections at every <h2 id>, <h3 id> and <dt id>, so a
 * search result links straight to the matching section. Headings marked with
 * data-no-index are skipped. No dependencies; Node 18+.
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'assets', 'js', 'search-index.js');

function findPages(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return findPages(full);
    return name.endsWith('.html') ? [full] : [];
  });
}

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', mdash: '—', ndash: '–', rarr: '→', larr: '←', hellip: '…' };

function toText(html) {
  return html
    .replace(/<(script|style|svg)\b[\s\S]*?<\/\1>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&(#\d+|#x[\da-f]+|\w+);/gi, (m, e) => {
      if (e[0] === '#') return String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
      return ENTITIES[e] ?? m;
    })
    .replace(/\s+/g, ' ')
    .trim();
}

const entries = [];

for (const file of [join(ROOT, 'index.html'), ...findPages(join(ROOT, 'pages'))]) {
  const html = readFileSync(file, 'utf8');
  const url = relative(ROOT, file).split(sep).join('/');
  const article = (html.match(/<article class="doc">([\s\S]*?)<\/article>/) || [])[1];
  if (!article) continue;

  const pageTitle = toText((article.match(/<h1[^>]*>([\s\S]*?)<\/h1>/) || [])[1] || url);
  const splitRe = /<(h2|h3|dt)\b([^>]*)>([\s\S]*?)<\/\1>/g;
  const cuts = [];
  let m;
  while ((m = splitRe.exec(article))) {
    const id = (m[2].match(/\bid="([^"]+)"/) || [])[1];
    if (!id || /data-no-index/.test(m[2])) continue;
    cuts.push({ id, title: toText(m[3]), start: m.index, bodyStart: m.index + m[0].length });
  }

  // Intro: everything before the first section.
  const introEnd = cuts.length ? cuts[0].start : article.length;
  entries.push({ u: url, p: pageTitle, s: '', t: toText(article.slice(0, introEnd)).replace(pageTitle, '').replace(/\s+/g, ' ').trim() });

  cuts.forEach((cut, i) => {
    const end = i + 1 < cuts.length ? cuts[i + 1].start : article.length;
    entries.push({ u: `${url}#${cut.id}`, p: pageTitle, s: cut.title, t: toText(article.slice(cut.bodyStart, end)) });
  });
}

const banner = '/* Generated by scripts/build-search-index.mjs — do not edit by hand. */\n';
writeFileSync(OUT, `${banner}window.SEARCH_INDEX = ${JSON.stringify(entries, null, 0)};\n`);
console.log(`Indexed ${entries.length} sections from ${new Set(entries.map((e) => e.u.split('#')[0])).size} pages → ${relative(ROOT, OUT)}`);
